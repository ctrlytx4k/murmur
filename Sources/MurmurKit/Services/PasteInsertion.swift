import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Everything on the pasteboard, in order, so it can be put back exactly.
struct PasteboardSnapshot {
    private var items: [[(type: NSPasteboard.PasteboardType, data: Data)]] = []

    static func take(_ pasteboard: NSPasteboard = .general) -> PasteboardSnapshot {
        var snapshot = PasteboardSnapshot()
        for item in pasteboard.pasteboardItems ?? [] {
            // Types that advertise no data (promises) cannot be saved; they are skipped.
            snapshot.items.append(item.types.compactMap { type in item.data(forType: type).map { (type, $0) } })
        }
        return snapshot
    }

    func restore(to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        let rebuilt = items.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in entries { item.setData(entry.data, forType: entry.type) }
            return item
        }
        if !rebuilt.isEmpty { pasteboard.writeObjects(rebuilt) }
    }

    func matches(_ other: PasteboardSnapshot) -> Bool {
        items.count == other.items.count && zip(items, other.items).allSatisfy { a, b in
            a.count == b.count && zip(a, b).allSatisfy { $0.type == $1.type && $0.data == $1.data }
        }
    }
}

/// Places text at the cursor of whatever app has focus: pasteboard plus a synthesized Cmd+V,
/// with the user's clipboard saved first and restored afterwards. Typing is the alternative.
public final class PasteInsertion: TextInsertionService {
    private let settings: SettingsStore
    private let pasteboard: NSPasteboard
    /// How long the front app gets to read the pasteboard before the clipboard is put back. It has to be
    /// generous: a busy app (a browser or Electron app mid-render) can take over a second to act on ⌘V,
    /// and if the clipboard is back by then it pastes the old contents and the take is lost.
    private let restoreDelay: Duration
    private let isTrusted: () -> Bool
    /// Presses ⌘V. Replaced in tests, which have no Accessibility permission and no app to paste into.
    private var pressPaste: () -> Void = {}
    /// A clipboard restore that has not happened yet: what to put back, and the change count our text was written at.
    private var pending: (saved: PasteboardSnapshot, ours: Int, task: Task<Void, Never>)?

    public init(
        settings: SettingsStore, pasteboard: NSPasteboard = .general, restoreDelay: Duration = .seconds(2),
        isTrusted: @escaping () -> Bool = { AXIsProcessTrusted() }, pressPaste: (() -> Void)? = nil
    ) {
        self.settings = settings
        self.pasteboard = pasteboard
        self.restoreDelay = restoreDelay
        self.isTrusted = isTrusted
        self.pressPaste = pressPaste ?? { [weak self] in self?.press(Self.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V), flags: .maskCommand) }
    }

    public var isSecureInputActive: Bool { IsSecureEventInputEnabled() }

    /// The restore still to come, if any. Tests wait on it.
    var restoreTask: Task<Void, Never>? { pending?.task }

    public func insert(_ text: String) async throws -> InsertionReceipt {
        let text = settings.addsTrailingSpace ? text + " " : text
        guard isTrusted() else {
            // Without Accessibility we cannot press keys. Leave the text where the user can paste it.
            cancelPendingRestore()
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            throw InsertionFailure.leftOnClipboard
        }
        if settings.insertMethod == .typing {
            type(text)
            return InsertionReceipt(text: text)
        }

        // If the last take's text is still on the clipboard waiting to be swapped back, the clipboard
        // to return to is the one saved then, not the dictated text sitting there now.
        let saved = pending.flatMap { pasteboard.changeCount == $0.ours ? $0.saved : nil } ?? PasteboardSnapshot.take(pasteboard)
        cancelPendingRestore()
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        // Markers clipboard managers honour, so the temporary entry is not kept in their history.
        pasteboard.setData(Data(), forType: .init("org.nspasteboard.TransientType"))
        pasteboard.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType"))
        let ours = pasteboard.changeCount

        pressPaste()
        // Long enough for the keys to be on their way before "Inserted" shows.
        try? await Task.sleep(for: .milliseconds(120))
        if settings.restoresClipboard {
            // Restored later and on its own, so a slow app still finds the text. Every path ends in a restore:
            // this task, the next take picking the snapshot up, or flushRestore() when the app quits.
            let delay = restoreDelay
            let task = Task { [weak self] in
                try? await Task.sleep(for: delay)
                guard !Task.isCancelled, let self else { return }
                self.restoreNow()
            }
            pending = (saved, ours, task)
        }
        return InsertionReceipt(text: text)
    }

    /// Puts the user's clipboard back at once. Called when the app quits with a restore still waiting.
    public func flushRestore() {
        pending?.task.cancel()
        restoreNow()
    }

    private func restoreNow() {
        guard let pending else { return }
        self.pending = nil
        // If something else wrote to the clipboard meanwhile, leave that alone.
        let untouched = pasteboard.changeCount == pending.ours
        if untouched { pending.saved.restore(to: pasteboard) }
        DebugLog.log(untouched ? "clipboard restored" : "clipboard left alone: something else was copied")
    }

    private func cancelPendingRestore() {
        pending?.task.cancel()
        pending = nil
    }

    /// Reverts only if the inserted text is still there unchanged, as far as Accessibility can tell.
    public func undo(_ receipt: InsertionReceipt) async -> Bool {
        guard isTrusted(), let value = Self.focusedText(), value.contains(receipt.text) else { return false }
        press(Self.keyCode(for: "z") ?? CGKeyCode(kVK_ANSI_Z), flags: .maskCommand)
        return true
    }

    // MARK: keys

    private func press(_ key: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down) else { continue }
            // Set explicitly, so a modifier the user is still holding does not turn Cmd+V into something else.
            event.flags = flags
            event.post(tap: .cghidEventTap)
            // A key that goes down and up in the same instant is missed by some apps.
            if down { usleep(12_000) }
        }
    }

    /// Typed Unicode events, in chunks that never split a character. Slower, but needs no clipboard.
    private func type(_ text: String) {
        let source = CGEventSource(stateID: .combinedSessionState)
        var chunk: [UniChar] = []
        func flush() {
            guard !chunk.isEmpty else { return }
            for down in [true, false] {
                guard let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: down) else { continue }
                event.flags = []
                event.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
                event.post(tap: .cghidEventTap)
            }
            chunk.removeAll(keepingCapacity: true)
            usleep(2_000)
        }
        for character in text {
            if character == "\n" {
                flush()
                // Shift+Return makes a line break in chat apps instead of sending the message.
                press(CGKeyCode(kVK_Return), flags: .maskShift)
                continue
            }
            let units = Array(String(character).utf16)
            if chunk.count + units.count > 20 { flush() }
            chunk += units
        }
        flush()
    }

    /// The key that produces this letter in the current layout. Cmd+V is matched by letter, so on
    /// Dvorak or AZERTY the physical key differs.
    static func keyCode(for letter: Character) -> CGKeyCode? {
        (0..<UInt16(127)).first { Shortcut.character(for: $0)?.lowercased() == String(letter) }.map { CGKeyCode($0) }
    }

    private static func focusedText() -> String? {
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(AXUIElementCreateSystemWide(), kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(focused as! AXUIElement, kAXValueAttribute as CFString, &value) == .success else { return nil }
        return value as? String
    }
}

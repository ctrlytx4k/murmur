// Experiment 2: text insertion.
//
//   insert clipboard [--current]          save/restore round-trips (seeded, or whatever is copied now)
//   insert target --name notes            countdown, then runs A, B, C into the focused field
//          [--only A,B,C] [--countdown 6] [--restore-delay-ms 200] [--type-delay-ms 2]
//          [--newline return|shift-return|unicode] [--no-ax-wake] [--no-prompt]
//
// Never logs clipboard or field contents, only types, sizes and comparisons.


let args = Args()
let mode = args.positional.first ?? "help"

// 400+ characters, one newline, precomposed and combining accents, curly quotes,
// CJK, and emoji that need surrogate pairs, skin tones, ZWJ and regional indicators.
let testBody =
    "Murmur spike check: café, naïve, jalapeño, Zürich, Ångström, smörgåsbord, "
    + "e\u{301} (combining acute), “curly quotes”, an em dash — and an ellipsis… "
    + "日本語 and Ελληνικά, plus emoji 😀 👍🏽 👩‍💻 🇨🇭 🏳️‍🌈 ✅.\n"
    + "Second line after the newline: the quick brown fox jumps over the lazy dog, "
    + "then does it again at 3:45 p.m. for $12.50 (roughly 10% off) while reading "
    + "path/to/file.swift, calling insert(text: \"hello\") and asking <why> & [how] {now}? "
    + "Tabs are skipped on purpose; backslash \\ and backtick ` are not. End of test string."

// MARK: pasteboard snapshot / restore

struct PBItem: Equatable {
    var entries: [(type: String, data: Data)]
    static func == (a: PBItem, b: PBItem) -> Bool {
        a.entries.count == b.entries.count
            && zip(a.entries, b.entries).allSatisfy { $0.type == $1.type && $0.data == $1.data }
    }
}

struct PBSnapshot {
    var items: [PBItem] = []
    var unreadable: [String] = []  // types advertised without data (promises, lazy providers)
    var bytes: Int { items.reduce(0) { $0 + $1.entries.reduce(0) { $0 + $1.data.count } } }
    var typeList: [[String]] { items.map { $0.entries.map(\.type) } }

    static func take(_ pb: NSPasteboard = .general) -> PBSnapshot {
        var snap = PBSnapshot()
        for item in pb.pasteboardItems ?? [] {
            var entries: [(type: String, data: Data)] = []
            for type in item.types {
                if let data = item.data(forType: type) {
                    entries.append((type.rawValue, data))
                } else {
                    snap.unreadable.append(type.rawValue)
                }
            }
            snap.items.append(PBItem(entries: entries))
        }
        return snap
    }

    func restore(to pb: NSPasteboard = .general) {
        pb.clearContents()
        let rebuilt = items.map { item -> NSPasteboardItem in
            let out = NSPasteboardItem()
            for entry in item.entries { out.setData(entry.data, forType: .init(entry.type)) }
            return out
        }
        if !rebuilt.isEmpty { pb.writeObjects(rebuilt) }
    }

    /// Describes the first difference, or nil when identical (item count, type order, bytes).
    func difference(from other: PBSnapshot) -> String? {
        if items.count != other.items.count { return "item count \(other.items.count) -> \(items.count)" }
        for (i, (a, b)) in zip(other.items, items).enumerated() {
            let ta = a.entries.map(\.type), tb = b.entries.map(\.type)
            if ta != tb {
                let lost = Set(ta).subtracting(tb).sorted(), gained = Set(tb).subtracting(ta).sorted()
                if lost.isEmpty && gained.isEmpty { return "item \(i): type order changed" }
                return "item \(i): lost \(lost) gained \(gained)"
            }
            for (x, y) in zip(a.entries, b.entries) where x.data != y.data {
                return "item \(i): bytes differ for \(x.type) (\(x.data.count) -> \(y.data.count))"
            }
        }
        return nil
    }
}

func putTextOnPasteboard(_ text: String) {
    let pb = NSPasteboard.general
    pb.clearContents()
    pb.setString(text, forType: .string)
    // nspasteboard.org markers so clipboard managers skip the temporary entry.
    pb.setData(Data(), forType: .init("org.nspasteboard.TransientType"))
    pb.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType"))
}

// MARK: seeds for clipboard tests

func makePNG(side: Int) -> (png: Data, tiff: Data) {
    let image = NSImage(size: NSSize(width: side, height: side))
    image.lockFocus()
    for i in 0..<64 {
        NSColor(hue: CGFloat(i) / 64, saturation: 0.8, brightness: 0.9, alpha: 1).setFill()
        NSRect(x: (i % 8) * side / 8, y: (i / 8) * side / 8, width: side / 8, height: side / 8).fill()
    }
    image.unlockFocus()
    let tiff = image.tiffRepresentation ?? Data()
    let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) ?? Data()
    return (png, tiff)
}

func seedPasteboard(_ kind: String) {
    let pb = NSPasteboard.general
    pb.clearContents()
    switch kind {
    case "empty":
        break
    case "text":
        pb.setString("plain seed text", forType: .string)
    case "rich":
        let attr = NSAttributedString(
            string: "Rich seed", attributes: [.font: NSFont.boldSystemFont(ofSize: 18), .foregroundColor: NSColor.red])
        let rtf = attr.rtf(from: NSRange(location: 0, length: attr.length), documentAttributes: [:]) ?? Data()
        let item = NSPasteboardItem()
        item.setData(rtf, forType: .rtf)
        item.setString("<b style=\"color:red\">Rich seed</b>", forType: .html)
        item.setString("Rich seed", forType: .string)
        pb.writeObjects([item])
    case "image":
        let img = makePNG(side: 1600)
        let item = NSPasteboardItem()
        item.setData(img.png, forType: .png)
        item.setData(img.tiff, forType: .tiff)
        pb.writeObjects([item])
    case "files":
        let dir = FileManager.default.temporaryDirectory
        let urls = ["spike-a.txt", "spike-b.txt"].map { dir.appendingPathComponent($0) }
        urls.forEach { try? Data("x".utf8).write(to: $0) }
        pb.writeObjects(urls as [NSURL])
    case "mixed":
        let text = NSPasteboardItem()
        text.setString("mixed seed", forType: .string)
        let image = NSPasteboardItem()
        image.setData(makePNG(side: 400).png, forType: .png)
        pb.writeObjects([text, image])
    case "large":
        let item = NSPasteboardItem()
        item.setData(Data(count: 64 << 20), forType: .init("dev.murmur.spike.blob"))
        item.setString("large seed", forType: .string)
        pb.writeObjects([item])
    default:
        fatalError("unknown seed \(kind)")
    }
}

// MARK: keyboard events

let eventSource = CGEventSource(stateID: .combinedSessionState)

func postKey(_ key: CGKeyCode, flags: CGEventFlags = []) {
    for down in [true, false] {
        guard let ev = CGEvent(keyboardEventSource: eventSource, virtualKey: key, keyDown: down) else { continue }
        ev.flags = flags
        ev.post(tap: .cghidEventTap)
    }
}

// MARK: accessibility helpers

func axCopy(_ el: AXUIElement, _ attr: String) -> (AnyObject?, AXError) {
    var value: CFTypeRef?
    let err = AXUIElementCopyAttributeValue(el, attr as CFString, &value)
    return (value, err)
}

func focusedElement() -> (AXUIElement?, AXError) {
    let (value, err) = axCopy(AXUIElementCreateSystemWide(), kAXFocusedUIElementAttribute)
    guard err == .success, let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return (nil, err) }
    return ((value as! AXUIElement), err)
}

func axValue(_ el: AXUIElement) -> String? { axCopy(el, kAXValueAttribute).0 as? String }

func axSelectedRange(_ el: AXUIElement) -> CFRange? {
    guard let v = axCopy(el, kAXSelectedTextRangeAttribute).0, CFGetTypeID(v) == AXValueGetTypeID() else { return nil }
    var range = CFRange()
    return AXValueGetValue(v as! AXValue, .cfRange, &range) ? range : nil
}

/// Chromium and Electron build their accessibility tree lazily. Poking these
/// attributes on the app element asks them to build it.
func wakeAccessibility(pid: pid_t) -> [String: Int32] {
    let app = AXUIElementCreateApplication(pid)
    var out: [String: Int32] = [:]
    for attr in ["AXManualAccessibility", "AXEnhancedUserInterface"] {
        out[attr] = AXUIElementSetAttributeValue(app, attr as CFString, kCFBooleanTrue).rawValue
    }
    return out
}

// MARK: strategies

protocol InsertionStrategy {
    var id: String { get }
    var name: String { get }
    /// Returns strategy-specific details for the log. Throws nothing: failures are data.
    func insert(_ text: String) -> [String: Any]
}

struct PasteStrategy: InsertionStrategy {
    let id = "A", name = "pasteboard + Cmd+V"
    let restoreDelayMs: Int
    func insert(_ text: String) -> [String: Any] {
        let t0 = monoMillis()
        let saved = PBSnapshot.take()
        let tSaved = monoMillis()
        putTextOnPasteboard(text)
        let ours = NSPasteboard.general.changeCount
        postKey(CGKeyCode(kVK_ANSI_V), flags: .maskCommand)
        usleep(useconds_t(restoreDelayMs * 1000))
        // If something else wrote to the pasteboard meanwhile, restoring would clobber it.
        let raced = NSPasteboard.general.changeCount != ours
        let tRestore = monoMillis()
        if !raced { saved.restore() }
        return [
            "snapshot_ms": round2(tSaved - t0),
            "restore_ms": round2(monoMillis() - tRestore),
            "restore_delay_ms": restoreDelayMs,
            "saved_bytes": saved.bytes,
            "saved_unreadable_types": saved.unreadable,
            "pasteboard_changed_under_us": raced,
        ]
    }
}

struct AccessibilityStrategy: InsertionStrategy {
    let id = "B", name = "AX selected text"
    func insert(_ text: String) -> [String: Any] {
        let (el, focusErr) = focusedElement()
        guard let el else { return ["ax_focus_error": focusErr.rawValue, "failed": "no focused AX element"] }
        var settable: DarwinBoolean = false
        AXUIElementIsAttributeSettable(el, kAXSelectedTextAttribute as CFString, &settable)
        let err = AXUIElementSetAttributeValue(el, kAXSelectedTextAttribute as CFString, text as CFString)
        return ["ax_settable": settable.boolValue, "ax_set_error": err.rawValue]
    }
}

struct TypedStrategy: InsertionStrategy {
    let id = "C", name = "typed Unicode events"
    let delayMs: Int
    let newline: String

    func post(_ chunk: [UniChar]) {
        for down in [true, false] {
            guard let ev = CGEvent(keyboardEventSource: eventSource, virtualKey: 0, keyDown: down) else { continue }
            ev.flags = []
            ev.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
            ev.post(tap: .cghidEventTap)
        }
        usleep(useconds_t(delayMs * 1000))
    }

    func insert(_ text: String) -> [String: Any] {
        var chunk: [UniChar] = []
        var events = 0
        func flush() {
            if !chunk.isEmpty { post(chunk); events += 1; chunk.removeAll(keepingCapacity: true) }
        }
        // Chunk on grapheme boundaries so a ZWJ emoji never straddles two events.
        for ch in text {
            if ch == "\n" && newline != "unicode" {
                flush()
                postKey(CGKeyCode(kVK_Return), flags: newline == "shift-return" ? .maskShift : [])
                usleep(useconds_t(delayMs * 1000))
                continue
            }
            let units = Array(String(ch).utf16)
            if chunk.count + units.count > 20 { flush() }
            chunk += units
        }
        flush()
        return ["key_events": events, "type_delay_ms": delayMs, "newline_as": newline]
    }
}

// MARK: verification

func literalRange(of needle: String, in haystack: String) -> NSRange {
    (haystack as NSString).range(of: needle, options: .literal)
}

/// exact | newline-variant | canonical-equivalent | mismatch | unverifiable
func judge(expected: String, fieldValue: String?) -> [String: Any] {
    guard let fieldValue else { return ["arrived": "unverifiable", "why": "no AX value on focused element"] }
    let r = literalRange(of: expected, in: fieldValue)
    if r.location != NSNotFound { return ["arrived": "exact", "found_at": r.location, "end": r.location + r.length] }
    for (label, nl) in [("\\r", "\r"), ("U+2028", "\u{2028}"), ("\\r\\n", "\r\n")] {
        let variant = expected.replacingOccurrences(of: "\n", with: nl)
        let vr = literalRange(of: variant, in: fieldValue)
        if vr.location != NSNotFound {
            return ["arrived": "newline-variant", "newline_became": label, "end": vr.location + vr.length]
        }
    }
    if fieldValue.precomposedStringWithCanonicalMapping.contains(expected.precomposedStringWithCanonicalMapping) {
        return ["arrived": "canonical-equivalent", "why": "Unicode normalization changed"]
    }
    // Find how far the text got: longest prefix of `expected` present after its first 8 units.
    let exp = Array(expected.utf16), got = Array(fieldValue.utf16)
    let head = String(utf16CodeUnits: exp, count: min(8, exp.count))
    let start = literalRange(of: head, in: fieldValue)
    guard start.location != NSNotFound else {
        return ["arrived": "mismatch", "why": "start of text not found", "field_len": got.count]
    }
    var i = 0
    while i < exp.count, start.location + i < got.count, exp[i] == got[start.location + i] { i += 1 }
    let expectedNext = String(utf16CodeUnits: Array(exp[i..<min(i + 6, exp.count)]), count: min(6, exp.count - i))
    return [
        "arrived": "mismatch", "matched_utf16_units": i, "of": exp.count,
        "expected_next": expectedNext.unicodeScalars.map { String(format: "U+%04X", $0.value) }.joined(separator: " "),
    ]
}

// MARK: modes

func runClipboard() {
    let log = ResultLog(experiment: "insert", label: "clipboard-" + args.string("name", "seeded"), args: args)
    let users = PBSnapshot.take()
    log.write("user_clipboard_saved", ["items": users.items.count, "bytes": users.bytes, "unreadable": users.unreadable])
    // --current: round-trip only what the user copied in another app (Finder files,
    // a Preview image, a spreadsheet range). Data then crosses a process boundary,
    // which the in-process seeds below do not exercise.
    let kinds = args.flag("current") ? ["current"] : ["empty", "text", "rich", "image", "files", "mixed", "large"]
    for kind in kinds {
        if kind != "current" { seedPasteboard(kind) }
        let t0 = monoMillis()
        let before = PBSnapshot.take()
        let t1 = monoMillis()
        putTextOnPasteboard(testBody)
        let t2 = monoMillis()
        before.restore()
        let t3 = monoMillis()
        let after = PBSnapshot.take()
        let diff = after.difference(from: before)
        log.write("roundtrip", [
            "seed": kind,
            "items": before.items.count,
            "types": before.typeList,
            "bytes": before.bytes,
            "unreadable": before.unreadable,
            "snapshot_ms": round2(t1 - t0),
            "restore_ms": round2(t3 - t2),
            "restored_exactly": diff == nil,
            "difference": diff ?? "",
        ])
    }
    if !args.flag("current") { users.restore() }
    let check = PBSnapshot.take().difference(from: users)
    log.write("user_clipboard_restored", ["exactly": check == nil, "difference": check ?? ""])
}

func ask(_ question: String) -> String {
    FileHandle.standardError.write(Data("\(question) ".utf8))
    return readLine()?.trimmingCharacters(in: .whitespaces) ?? ""
}

func runTarget() {
    let target = args.string("name", "unnamed")
    let log = ResultLog(experiment: "insert", label: target, args: args)
    let only = Set(args.string("only", "A,B,C").split(separator: ",").map(String.init))
    let strategies: [any InsertionStrategy] = [
        PasteStrategy(restoreDelayMs: args.int("restore-delay-ms", 200)),
        AccessibilityStrategy(),
        TypedStrategy(delayMs: args.int("type-delay-ms", 2), newline: args.string("newline", "return")),
    ].filter { only.contains($0.id) }

    log.write("permissions", ["accessibility": AXIsProcessTrusted()])
    if !AXIsProcessTrusted() {
        _ = AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary)
        log.write("blocked", ["cause": "Accessibility not granted to the launching app; grant it and rerun"])
        exit(2)
    }

    let countdown = args.int("countdown", 6)
    for s in stride(from: countdown, to: 0, by: -1) {
        FileHandle.standardError.write(Data("Click into the \(target) text field... \(s)\n".utf8))
        sleep(1)
    }

    let front = NSWorkspace.shared.frontmostApplication
    var targetInfo: [String: Any] = ["bundle": front?.bundleIdentifier ?? "none"]
    if let pid = front?.processIdentifier, !args.flag("no-ax-wake") {
        targetInfo["ax_wake"] = wakeAccessibility(pid: pid)
        usleep(400_000)
    }
    if let el = focusedElement().0 {
        targetInfo["role"] = axCopy(el, kAXRoleAttribute).0 as? String ?? ""
        targetInfo["subrole"] = axCopy(el, kAXSubroleAttribute).0 as? String ?? ""
        targetInfo["has_ax_value"] = axValue(el) != nil
    } else {
        targetInfo["role"] = "no focused AX element"
    }
    log.write("target", targetInfo)

    // Known clipboard contents so "restored exactly" means something.
    let users = PBSnapshot.take()
    seedPasteboard("mixed")
    let seed = PBSnapshot.take()

    var needsHuman: [String] = []
    for strategy in strategies {
        let text = "[\(strategy.id)] " + testBody
        let secure = IsSecureEventInputEnabled()
        if secure {
            // Reported, then attempted anyway: knowing what each strategy does here is the point.
            log.write("secure_input_detected", ["strategy": strategy.id])
        }
        let t0 = monoMillis()
        var row = strategy.insert(text)
        row["call_ms"] = round2(monoMillis() - t0)

        // Poll for arrival so we get a time and do not judge too early.
        var verdict: [String: Any] = [:]
        var arrivedAfter: Double?
        let deadline = monoMillis() + 3000
        repeat {
            usleep(25_000)
            verdict = judge(expected: text, fieldValue: focusedElement().0.flatMap(axValue))
            if verdict["arrived"] as? String == "exact" { arrivedAfter = monoMillis() - t0; break }
        } while monoMillis() < deadline && verdict["arrived"] as? String != "unverifiable"
        row.merge(verdict) { a, _ in a }
        if let arrivedAfter { row["arrived_after_ms"] = round2(arrivedAfter) }

        if let end = verdict["end"] as? Int, let sel = focusedElement().0.flatMap(axSelectedRange) {
            row["cursor_at_end"] = sel.location == end && sel.length == 0
        } else {
            row["cursor_at_end"] = "unverifiable"
        }

        usleep(300_000)
        let diff = PBSnapshot.take().difference(from: seed)
        row["clipboard_restored_exactly"] = diff == nil
        row["clipboard_difference"] = diff ?? ""
        row["strategy"] = strategy.id
        row["strategy_name"] = strategy.name
        row["target"] = target
        row["secure_input"] = secure
        row["text_chars"] = text.count
        row["text_utf16"] = text.utf16.count
        log.write("result", row)
        if verdict["arrived"] as? String != "exact" { needsHuman.append(strategy.id) }
        seed.restore()
        usleep(500_000)
    }

    users.restore()
    log.write("user_clipboard_restored", ["exactly": PBSnapshot.take().difference(from: users) == nil])

    if !args.flag("no-prompt") {
        NSSound.beep()
        FileHandle.standardError.write(Data("\nBack in this terminal. Answers are free text, logged as typed.\n".utf8))
        for id in needsHuman {
            log.write("human", [
                "strategy": id,
                "arrived_exactly": ask("[\(id)] could not be auto-verified. Did the full text arrive exactly (emoji, accents, newline)? y/n + notes:"),
            ])
        }
        log.write("human", [
            "flicker": ask("Which strategies showed visible flicker or selection flashes? (e.g. A, none):"),
            "cursor": ask("After each insert, was the cursor at the end of the inserted text? Note any that were not:"),
            "notes": ask("Anything else odd (message sent early, command ran, beep, popup)?"),
        ])
    }
}

switch mode {
case "clipboard": runClipboard()
case "target": runTarget()
default:
    print("usage: insert clipboard | insert target --name <target> [--only A,B,C] [--countdown 6]")
    print("test string: \(testBody.count) characters, \(testBody.utf16.count) UTF-16 units")
}
